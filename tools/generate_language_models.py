"""Generate stable bindings from the reviewed lingua 1.8.0 language manifest.
Run from any directory; the native ID is the two lowercase ISO-639-1 ASCII bytes.
"""
import json
from pathlib import Path
root = Path(__file__).resolve().parent.parent
rows = json.loads((root / 'tools/languages.json').read_text())
base = root / 'lingua-core/src/commonMain/kotlin/com/zhangke/lingua'
header = '// Generated by tools/generate_language_models.py; edit tools/languages.json.\n'
for key, name in [('iso1', 'IsoCode6391'), ('iso3', 'IsoCode6393')]:
    values = ',\n'.join(f'    {r[key].upper()}("{r[key]}")' for r in rows)
    (base / f'{name}.kt').write_text(header + f'''package com.zhangke.lingua

/** ISO codes for the 75 languages supported by lingua-rs 1.8.0. */
public enum class {name}(public val code: String) {{
{values};

    override fun toString(): String = code

    public companion object {{
        /** Parses an ISO code case-insensitively; rejects unsupported codes. */
        public fun fromCode(code: String): {name} =
            entries.firstOrNull {{ it.code.equals(code, ignoreCase = true) }}
                ?: throw IllegalArgumentException("Unsupported ISO code: $code")
    }}
}}
''')
values = ',\n'.join(f'    {r["name"].upper()}(IsoCode6391.{r["iso1"].upper()}, IsoCode6393.{r["iso3"].upper()})' for r in rows)
out = header + f'''package com.zhangke.lingua

public enum class Language(
    public val isoCode6391: IsoCode6391,
    public val isoCode6393: IsoCode6393,
) {{
{values};

    // Stable wire ID, independent of either enum's ordinal.
    internal val nativeId: Int
        get() = (isoCode6391.code[0].code shl 8) or isoCode6391.code[1].code

    public companion object {{
        public fun all(): Set<Language> = entries.toSet()
        public fun allSpokenOnes(): Set<Language> = all() - LATIN
'''
for script in ['Arabic','Cyrillic','Devanagari','Latin']:
    names=', '.join(r['name'].upper() for r in rows if script in r['scripts'])
    out+=f'        public fun allWith{script}Script(): Set<Language> = setOf({names})\n'
counts={s:sum(s in r['scripts'] for r in rows) for r in rows for s in r['scripts']}
names=', '.join(r['name'].upper() for r in rows if len(r['scripts'])==1 and counts[r['scripts'][0]]==1)
out+=f'        public fun allWithSingleUniqueScript(): Set<Language> = setOf({names})\n'
out+='''
        public fun fromIsoCode6391(code: IsoCode6391): Language = entries.first { it.isoCode6391 == code }
        public fun fromIsoCode6393(code: IsoCode6393): Language = entries.first { it.isoCode6393 == code }

        internal fun fromNativeId(id: Int): Language = entries.firstOrNull { it.nativeId == id }
            ?: throw IllegalStateException("Unknown native language ID: $id")
    }
}
'''
(base/'Language.kt').write_text(out)
rs=header+'use lingua::Language;\nuse crate::core::{BridgeError, Result};\n\n'
rs+='pub fn language_from_id(id: i32) -> Result<Language> {\n    match id {\n'
for r in rows:
    id=int.from_bytes(r['iso1'].encode(),'big')
    rs+=f'        {id} => Ok(Language::{r["name"]}),\n'
rs+='        _ => Err(BridgeError::Argument("Invalid language ID".into())),\n    }\n}\n\n'
rs+='pub fn language_id(language: Language) -> i32 {\n    match language {\n'
for r in rows:
    rs+=f'        Language::{r["name"]} => {int.from_bytes(r["iso1"].encode(),"big")},\n'
rs+='    }\n}\n'
(root/'native/src/language.rs').write_text(rs)
